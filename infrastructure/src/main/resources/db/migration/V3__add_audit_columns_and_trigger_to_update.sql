-- CUSTOMER
ALTER TABLE tb_customer
    ADD COLUMN created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ADD COLUMN updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL;

-- BOOK
ALTER TABLE tb_book
    ADD COLUMN created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ADD COLUMN updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,

    -- Audit columns
    ADD COLUMN created_by VARCHAR(36) REFERENCES tb_user(id) ON DELETE SET NULL,
    ADD COLUMN updated_by VARCHAR(36) REFERENCES tb_user(id) ON DELETE SET NULL;

-- LOAN
ALTER TABLE tb_loan
    ADD COLUMN created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ADD COLUMN updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,

    -- Audit columns
    ADD COLUMN created_by VARCHAR(36) REFERENCES tb_user(id) ON DELETE SET NULL,
    ADD COLUMN updated_by VARCHAR(36) REFERENCES tb_user(id) ON DELETE SET NULL;

-- TRIGGERS
CREATE OR REPLACE FUNCTION automatic_updated_at()
    RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- BOOK
CREATE TRIGGER trigger_book_automatic_updated_at
    BEFORE UPDATE ON tb_book
    FOR EACH ROW
EXECUTE FUNCTION automatic_updated_at();

-- LOAN
CREATE TRIGGER trigger_loan_automatic_updated_at
    BEFORE UPDATE ON tb_loan
    FOR EACH ROW
EXECUTE FUNCTION automatic_updated_at();