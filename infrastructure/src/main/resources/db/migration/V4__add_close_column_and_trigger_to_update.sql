-- LOAN
ALTER TABLE tb_loan
    ADD COLUMN closed_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NULL;

-- TRIGGERS
CREATE OR REPLACE FUNCTION automatic_updated_at()
    RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- CUSTOMER
CREATE TRIGGER trigger_book_automatic_updated_at
    BEFORE UPDATE ON tb_customer
    FOR EACH ROW
EXECUTE FUNCTION automatic_updated_at();